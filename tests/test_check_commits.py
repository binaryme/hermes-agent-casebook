import contextlib
import io
import subprocess
import unittest

from harness import check_commits

GOOD = "docs(entries): add one entry\n\nOperators need it because the default surprises them.\n"


class MessageTests(unittest.TestCase):
    def assert_clean(self, message):
        self.assertEqual(check_commits.message_problems(message), [])

    def assert_problem(self, message, fragment):
        problems = check_commits.message_problems(message)
        self.assertTrue(any(fragment in problem for problem in problems), problems)

    def test_a_good_message_passes(self):
        self.assert_clean(GOOD)

    def test_signed_off_by_is_allowed(self):
        self.assert_clean(GOOD + "\nSigned-off-by: Example Person <person@example.com>\n")

    def test_breaking_marker_and_scope_are_allowed(self):
        self.assert_clean("feat(harness)!: change the token format\n\nRepros now print two tokens.\n")

    def test_unknown_type_fails(self):
        self.assert_problem("update stuff\n\nBecause.\n", "Conventional Commits")

    def test_missing_body_fails(self):
        self.assert_problem("docs: add a page\n", "body is empty")

    def test_header_must_be_followed_by_a_blank_line(self):
        self.assert_problem("docs: add a page\nBecause.\n", "blank line")

    def test_long_header_fails(self):
        self.assert_problem("docs: " + "x" * 100 + "\n\nBecause.\n", "longer than")

    def test_co_authored_by_trailer_fails(self):
        self.assert_problem(GOOD + "\nCo-Authored-By: Someone <someone@example.com>\n", "not allowed")

    def test_co_authored_by_anywhere_fails(self):
        self.assert_problem(
            "docs: add a page\n\nCo-Authored-By: Someone <someone@example.com>\n\nMore text after it.\n",
            "co-author",
        )

    def test_generated_with_line_fails(self):
        self.assert_problem(GOOD + "\nGenerated with some tool\n", "generator")

    def test_other_trailers_fail(self):
        self.assert_problem(GOOD + "\nReviewed-by: Someone <someone@example.com>\n", "Reviewed-by")

    def test_prose_with_a_colon_is_not_a_trailer(self):
        self.assert_clean("docs: add a page\n\nChecked locally on 2026-11-13: it matched.\n")

    def test_the_word_generated_in_prose_is_fine(self):
        self.assert_clean("docs: add a page\n\nINDEX.md is generated by stamp.py from the front matter.\n")


class MainTests(unittest.TestCase):
    def fake_git(self, messages):
        def run(command, **kwargs):
            stdout = "".join(
                f"{sha}{check_commits.FIELD_SEPARATOR}{message}{check_commits.RECORD_SEPARATOR}\n"
                for sha, message in messages
            )
            return subprocess.CompletedProcess(command, 0, stdout=stdout, stderr="")
        return run

    def run_main(self, messages):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = check_commits.main(["HEAD"], run=self.fake_git(messages))
        return code, out.getvalue()

    def test_all_good_commits_pass(self):
        code, out = self.run_main([("a" * 40, GOOD), ("b" * 40, GOOD)])
        self.assertEqual(code, 0)
        self.assertIn("2 commits checked", out)

    def test_one_bad_commit_fails_and_is_named(self):
        code, out = self.run_main([("a" * 40, GOOD), ("c" * 40, "wip\n")])
        self.assertEqual(code, 1)
        self.assertIn("cccccccccccc:", out)

    def test_git_failure_exits_two(self):
        def failing(command, **kwargs):
            raise subprocess.CalledProcessError(128, command, stderr="bad revision")

        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            code = check_commits.main(["nope"], run=failing)
        self.assertEqual(code, 2)


if __name__ == "__main__":
    unittest.main()
